/**
 * ============================================================================
 *  PLACEHOLDER ARTWORK GENERATOR
 * ============================================================================
 *  Writes the on-brand SVG stand-ins used by the gallery and the About
 *  portrait, so the layout looks finished before Michal's real photos arrive.
 *
 *  Run with:  node scripts/make-placeholders.mjs
 *
 *  Each piece is drawn the same way a real relief photograph reads: a light
 *  wall, a panel a couple of steps darker, a soft cast shadow, then folds and
 *  ridges shaded with light-to-dark gradients so they look three-dimensional
 *  rather than like flat line art. Everything stays inside the site palette.
 *
 *  ⚠️ These files are DISPOSABLE. As real photos come in, drop them into
 *  public/images/gallery/ and update `gallery` in src/data/site.js. Once every
 *  item points at a real photo, this script and the SVGs it produces can be
 *  deleted outright.
 * ============================================================================
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const galleryDir = resolve(root, 'public/images/gallery');
mkdirSync(galleryDir, { recursive: true });

/* Palette, kept in step with tailwind.config.js */
const C = {
  wallTop: '#FCFAF6',
  wallBottom: '#EDE3D5',
  shadow: '#9C8468',
  ink: '#2B2420',
};

/** Paper grain + soft shadow blur, namespaced per file. */
const defs = (id, extra = '', grainFreq = 0.8, grainSlope = 0.07) => `
  <defs>
    <linearGradient id="wall-${id}" x1="0.1" y1="0" x2="0.4" y2="1">
      <stop offset="0" stop-color="${C.wallTop}"/>
      <stop offset="1" stop-color="${C.wallBottom}"/>
    </linearGradient>
    <filter id="soft-${id}" x="-40%" y="-40%" width="180%" height="180%">
      <feGaussianBlur stdDeviation="22"/>
    </filter>
    <filter id="grain-${id}" x="0" y="0" width="100%" height="100%">
      <feTurbulence type="fractalNoise" baseFrequency="${grainFreq}" numOctaves="3" result="n"/>
      <feColorMatrix in="n" type="saturate" values="0"/>
      <feComponentTransfer><feFuncA type="linear" slope="${grainSlope}"/></feComponentTransfer>
      <feComposite operator="in" in2="SourceGraphic"/>
    </filter>${extra}
  </defs>`;

/** Vertical light→dark gradient, used to shade a single fold or ridge. */
const ridgeGradient = (id, light, dark, horizontal = false) => `
    <linearGradient id="${id}" x1="${horizontal ? 0 : 0}" y1="${horizontal ? 0 : 0}" x2="${horizontal ? 1 : 0}" y2="${horizontal ? 0 : 1}">
      <stop offset="0" stop-color="${light}"/>
      <stop offset="0.55" stop-color="${dark}"/>
      <stop offset="1" stop-color="${light}"/>
    </linearGradient>`;

const scene = ({ id, w, h, panel, panelFill, content, defsExtra = '', grainFreq, grainSlope }) => {
  const [px, py, pw, ph] = panel;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" role="img">
  <!-- PLACEHOLDER ARTWORK — generated by scripts/make-placeholders.mjs. Replace with a real photo. -->
${defs(id, defsExtra, grainFreq, grainSlope)}
  <rect width="${w}" height="${h}" fill="url(#wall-${id})"/>
  <rect x="${px + 14}" y="${py + 22}" width="${pw}" height="${ph}" fill="${C.shadow}" opacity="0.42" filter="url(#soft-${id})"/>
  <rect x="${px}" y="${py}" width="${pw}" height="${ph}" fill="${panelFill}"/>
${content}
  <rect x="${px}" y="${py}" width="${pw}" height="${ph}" fill="none" stroke="${C.shadow}" stroke-opacity="0.22"/>
  <rect width="${w}" height="${h}" fill="${C.ink}" filter="url(#grain-${id})" opacity="0.6"/>
</svg>
`;
};

const pieces = [];

/* ------------------------------------------------------------------------
 * 01 — horizontal textile folds, sand
 * --------------------------------------------------------------------- */
{
  const panel = [318, 190, 560, 490];
  const [px, py, pw, ph] = panel;
  const bands = 8;
  const bandH = ph / bands;
  let grads = '';
  let body = '';
  for (let i = 0; i < bands; i++) {
    const gid = `f1-${i}`;
    grads += ridgeGradient(gid, '#F6EFE4', i % 2 ? '#BFA484' : '#C9B294');
    const y = py + i * bandH;
    const wob = i % 2 ? 22 : -18;
    body += `  <path d="M ${px} ${y + bandH} C ${px + pw * 0.3} ${y + bandH + wob} ${px + pw * 0.68} ${y + bandH - wob} ${px + pw} ${y + bandH * 0.72}
             L ${px + pw} ${y} C ${px + pw * 0.7} ${y + wob * 0.6} ${px + pw * 0.32} ${y - wob * 0.6} ${px} ${y} Z" fill="url(#${gid})"/>\n`;
  }
  // two soft vertical drapes crossing the folds
  grads += ridgeGradient('f1-v1', '#FBF6EE', '#C2A886', true);
  body += `  <path d="M ${px + 120} ${py} C ${px + 168} ${py + 150} ${px + 92} ${py + 300} ${px + 150} ${py + ph}
           L ${px + 232} ${py + ph} C ${px + 178} ${py + 300} ${px + 250} ${py + 150} ${px + 205} ${py} Z" fill="url(#f1-v1)" opacity="0.62"/>\n`;
  body += `  <path d="M ${px + 340} ${py} C ${px + 392} ${py + 160} ${px + 314} ${py + 320} ${px + 372} ${py + ph}
           L ${px + 452} ${py + ph} C ${px + 398} ${py + 320} ${px + 470} ${py + 160} ${px + 424} ${py} Z" fill="url(#f1-v1)" opacity="0.5"/>\n`;

  pieces.push({
    file: 'piece-01.svg',
    svg: scene({
      id: 'p1',
      w: 1200,
      h: 900,
      panel,
      panelFill: '#D3BC9F',
      defsExtra: grads,
      content: body,
    }),
  });
}

/* ------------------------------------------------------------------------
 * 02 — white plaster, vertical ridges, portrait panel
 * --------------------------------------------------------------------- */
{
  const panel = [428, 140, 344, 580];
  const [px, py, pw, ph] = panel;
  const ridges = 9;
  const rw = pw / ridges;
  let grads = '';
  let body = '';
  for (let i = 0; i < ridges; i++) {
    const gid = `f2-${i}`;
    grads += ridgeGradient(gid, '#FEFCF9', '#CFBEA6', true);
    const x = px + i * rw;
    body += `  <path d="M ${x} ${py} C ${x + rw * 0.5} ${py + 140} ${x - rw * 0.35} ${py + 400} ${x + rw * 0.28} ${py + ph}
             L ${x + rw} ${py + ph} C ${x + rw * 0.4} ${py + 400} ${x + rw * 1.4} ${py + 140} ${x + rw} ${py} Z" fill="url(#${gid})"/>\n`;
  }
  // soft central highlight, as if lit from the left
  body += `  <ellipse cx="${px + pw * 0.42}" cy="${py + ph * 0.44}" rx="${pw * 0.42}" ry="${ph * 0.34}" fill="#FFFDFA" opacity="0.34"/>\n`;

  pieces.push({
    file: 'piece-02.svg',
    svg: scene({
      id: 'p2',
      w: 1200,
      h: 900,
      panel,
      panelFill: '#E8DCC9',
      defsExtra: grads,
      content: body,
      grainFreq: 1.0,
    }),
  });
}

/* ------------------------------------------------------------------------
 * 03 — organic linework, sand panel with wood-brown lines
 * --------------------------------------------------------------------- */
{
  const panel = [268, 210, 664, 460];
  const [px, py, pw, ph] = panel;
  // Everything is clipped to the panel — without this the contour lines run
  // off the artwork and onto the wall.
  let body = `  <g clip-path="url(#clip-p3)">\n`;
  // a soft light wash across the top, as a gradient rather than a hard edge
  body += `  <rect x="${px}" y="${py}" width="${pw}" height="${ph}" fill="url(#p3-wash)"/>\n`;
  // stacked contour lines, thicker at the bottom so they read as relief
  for (let i = 0; i < 18; i++) {
    const off = i * 26;
    const sw = (3.4 - i * 0.13).toFixed(2);
    const op = (0.5 - i * 0.018).toFixed(3);
    body += `    <path d="M ${px - 20} ${py + ph - 30 - off} C ${px + 190} ${py + ph - 200 - off} ${px + 320} ${py + ph - 120 - off} ${px + 452} ${py + ph - 260 - off} C ${px + 556} ${py + ph - 350 - off} ${px + 610} ${py + ph - 300 - off} ${px + pw + 20} ${py + ph - 372 - off}"
             fill="none" stroke="#8B6B4A" stroke-opacity="${op}" stroke-width="${sw}" stroke-linecap="round"/>\n`;
  }
  body += `  </g>\n`;

  pieces.push({
    file: 'piece-03.svg',
    svg: scene({
      id: 'p3',
      w: 1200,
      h: 900,
      panel,
      panelFill: '#DCC9AE',
      defsExtra: `
    <clipPath id="clip-p3">
      <rect x="${px}" y="${py}" width="${pw}" height="${ph}"/>
    </clipPath>
    <linearGradient id="p3-wash" x1="0" y1="0" x2="0.2" y2="1">
      <stop offset="0" stop-color="#FBF6EC" stop-opacity="0.72"/>
      <stop offset="0.55" stop-color="#FBF6EC" stop-opacity="0.1"/>
      <stop offset="1" stop-color="#8B6B4A" stop-opacity="0.16"/>
    </linearGradient>`,
      content: body,
    }),
  });
}

/* ------------------------------------------------------------------------
 * 04 — circular relief, concentric rings
 * --------------------------------------------------------------------- */
{
  const panel = [340, 165, 520, 530];
  const cx = 600;
  const cy = 430;
  let body = '';
  for (let i = 0; i < 13; i++) {
    const r = 232 - i * 17;
    const light = i % 2 === 0;
    body += `  <circle cx="${cx}" cy="${cy}" r="${r}" fill="none" stroke="${light ? '#F7F0E4' : '#B99E7C'}" stroke-opacity="${light ? 0.85 : 0.6}" stroke-width="${(13 - i * 0.5).toFixed(1)}"/>\n`;
  }
  body += `  <circle cx="${cx}" cy="${cy}" r="46" fill="#FBF6EE"/>\n`;
  body += `  <circle cx="${cx}" cy="${cy}" r="46" fill="none" stroke="#8B6B4A" stroke-opacity="0.3" stroke-width="2.5"/>\n`;
  // directional shading across the whole relief
  body += `  <rect x="${panel[0]}" y="${panel[1]}" width="${panel[2]}" height="${panel[3]}" fill="url(#p4-shade)"/>\n`;

  pieces.push({
    file: 'piece-04.svg',
    svg: scene({
      id: 'p4',
      w: 1200,
      h: 900,
      panel,
      panelFill: '#E0D2BB',
      defsExtra: `
    <linearGradient id="p4-shade" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#FFFDF9" stop-opacity="0.4"/>
      <stop offset="0.55" stop-color="#FFFDF9" stop-opacity="0"/>
      <stop offset="1" stop-color="#8B6B4A" stop-opacity="0.24"/>
    </linearGradient>`,
      content: body,
    }),
  });
}

/* ------------------------------------------------------------------------
 * 05 — desert triptych, three tonal panels
 * --------------------------------------------------------------------- */
{
  const tones = ['#EADCC6', '#DAC5A6', '#C6AC88'];
  const panelY = 258;
  const panelH = 384;
  let grads = '';
  let body = '';
  tones.forEach((tone, i) => {
    const x = 268 + i * 232;
    const gid = `f5-${i}`;
    grads += ridgeGradient(gid, '#FBF6ED', tone, true);
    body += `  <rect x="${x + 12}" y="${panelY + 18}" width="200" height="${panelH}" fill="${C.shadow}" opacity="0.34" filter="url(#soft-p5)"/>\n`;
    body += `  <rect x="${x}" y="${panelY}" width="200" height="${panelH}" fill="${tone}"/>\n`;
    // three soft ridges per panel
    for (let k = 0; k < 3; k++) {
      const rx = x + 22 + k * 58;
      body += `  <path d="M ${rx} ${panelY} C ${rx + 30} ${panelY + 120} ${rx - 18} ${panelY + 260} ${rx + 22} ${panelY + panelH}
               L ${rx + 46} ${panelY + panelH} C ${rx + 6} ${panelY + 260} ${rx + 54} ${panelY + 120} ${rx + 24} ${panelY} Z" fill="url(#${gid})" opacity="0.7"/>\n`;
    }
    body += `  <rect x="${x}" y="${panelY}" width="200" height="${panelH}" fill="none" stroke="#8B6B4A" stroke-opacity="0.24"/>\n`;
  });

  // the shared "panel" here is invisible: the triptych provides its own panels
  pieces.push({
    file: 'piece-05.svg',
    svg: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 900" width="1200" height="900" role="img">
  <!-- PLACEHOLDER ARTWORK — generated by scripts/make-placeholders.mjs. Replace with a real photo. -->
${defs('p5', grads)}
  <rect width="1200" height="900" fill="url(#wall-p5)"/>
${body}
  <rect width="1200" height="900" fill="${C.ink}" filter="url(#grain-p5)" opacity="0.6"/>
</svg>
`,
  });
}

for (const p of pieces) {
  writeFileSync(resolve(galleryDir, p.file), p.svg, 'utf8');
  console.log('wrote', 'public/images/gallery/' + p.file);
}

